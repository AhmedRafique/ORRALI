export function getCityBuildingsByLanguage(languageId: LangCode): InteractiveMapBuilding[] {
  return CITY_MAP_BUILDINGS.filter((b) => b.languageId === languageId);
}

export function getBuildingById(buildingId: string): InteractiveMapBuilding | undefined {
  return CITY_MAP_BUILDINGS.find((b) => b.id === buildingId);
}

export function getBuildingsByDistrict(
  languageId: LangCode,
  district: DistrictKind
): InteractiveMapBuilding[] {
  return CITY_MAP_BUILDINGS.filter(
    (b) => b.languageId === languageId && b.district === district
  );
}
