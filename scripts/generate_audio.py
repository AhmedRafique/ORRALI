import asyncio
import json
import os
import ssl
import edge_tts

# Standard secure SSL context by default; optional corporate proxy override via INSECURE_SSL=1
if os.environ.get("INSECURE_SSL") == "1":
    unverified = ssl._create_unverified_context()
    edge_tts.voices._SSL_CTX = unverified
    edge_tts.communicate._SSL_CTX = unverified

FRENCH_VOICE = "fr-FR-VivienneMultilingualNeural"
GERMAN_VOICE = "de-DE-TanjaNeural"
SPANISH_VOICE = "es-ES-ElviraNeural"

def get_lang_and_voice(item_id):
    if item_id.startswith("fr-"):
        return "fr", FRENCH_VOICE
    if item_id.startswith("es-"):
        return "es", SPANISH_VOICE
    return "de", GERMAN_VOICE

async def generate_item(item, sem):
    item_id = item["id"]
    target = item["target"]
    lang_dir, voice = get_lang_and_voice(item_id)

    out_dir = os.path.join("assets", "audio", lang_dir)
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, f"{item_id}.mp3")

    if os.path.exists(out_file) and os.path.getsize(out_file) > 1000:
        return item_id, out_file

    async with sem:
        for attempt in range(3):
            try:
                tts = edge_tts.Communicate(target, voice, rate="-4%")
                await tts.save(out_file)
                return item_id, out_file
            except Exception as e:
                if attempt == 2:
                    print(f"Failed to generate {item_id}: {e}")
                await asyncio.sleep(1)
        return item_id, None

async def main():
    with open("scripts/items.json", "r", encoding="utf-8") as f:
        items = json.load(f)

    print(f"Generating studio neural audio for {len(items)} items...")
    sem = asyncio.Semaphore(5)
    tasks = [generate_item(item, sem) for item in items]
    results = await asyncio.gather(*tasks)

    success_count = sum(1 for _, path in results if path and os.path.exists(path))
    print(f"Successfully generated {success_count}/{len(items)} audio files.")

    # Write src/audioMap.ts
    map_lines = ["// Auto-generated by scripts/generate_audio.py - DO NOT EDIT MANUALLY"]
    map_lines.append("export const AUDIO_ASSETS: Record<string, any> = {")
    for item in items:
        item_id = item["id"]
        lang_dir, _ = get_lang_and_voice(item_id)
        file_path = f"../assets/audio/{lang_dir}/{item_id}.mp3"
        local_disk_path = os.path.join("assets", "audio", lang_dir, f"{item_id}.mp3")
        if os.path.exists(local_disk_path):
            map_lines.append(f"  '{item_id}': require('{file_path}'),")
    map_lines.append("};\n")

    with open("src/audioMap.ts", "w", encoding="utf-8") as f:
        f.write("\n".join(map_lines))

    print(f"Generated src/audioMap.ts with {success_count} mappings.")

if __name__ == "__main__":
    asyncio.run(main())
